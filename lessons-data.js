export function getOpenLesson() {
  const openLessons = lessons.filter((lesson) => lesson.status === 'open');
  return openLessons.at(-1) ?? lessons[0];
}

export function getLessonById(id) {
  return lessons.find((lesson) => lesson.id === id);
}
